// Helper function to interpolate LMS values for exact age
export function getLMSForAge(
  lmsData: typeof weightForAgeBoys,
  ageMonths: number
) {
  // Find surrounding data points
  let lower = lmsData[0];
  let upper = lmsData[lmsData.length - 1];
  
  for (let i = 0; i < lmsData.length - 1; i++) {
    if (ageMonths >= lmsData[i].ageMonths && ageMonths <= lmsData[i + 1].ageMonths) {
      lower = lmsData[i];
      upper = lmsData[i + 1];
      break;
    }
  }
  
  // Linear interpolation
  if (lower.ageMonths === upper.ageMonths) {
    return lower;
  }
  
  const ratio = (ageMonths - lower.ageMonths) / (upper.ageMonths - lower.ageMonths);
  
  return {
    ageMonths,
    L: lower.L + (upper.L - lower.L) * ratio,
    M: lower.M + (upper.M - lower.M) * ratio,
    S: lower.S + (upper.S - lower.S) * ratio,
  };
}
